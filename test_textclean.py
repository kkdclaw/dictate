"""Тесты правил чистки: `python3 test_textclean.py`. Без MLX и rumps."""
from textclean import strip_loops

SPEECH = [{"text": " x", "start": 0.0, "end": 1.0, "no_speech_prob": 0.05, "avg_logprob": -0.3}]


def keep(text, segments=None):
    out, cut = strip_loops(text, segments)
    assert out == text and not cut, (text, out, cut)


def cuts(text, expect, segments=None):
    out, cut = strip_loops(text, segments)
    assert out == expect and cut, (text, out, cut)


# настоящая речь с повторами — не трогаем (регресс 0.15.1)
keep("нет нет нет нет нет, я не согласен")
keep("ха-ха-ха-ха-ха, смешно")
keep("1 000 000 000 000 рублей")
keep("да да да да да да да, точно")
# галлюцинации-петли — режем, остальное остаётся
cuts("ratos" * 40 + " нормальная речь", "нормальная речь")
cuts("начало фразы secular " * 1 + "secular " * 20 + "конец", "начало фразы конец")
cuts("ха" * 30 + " ладно", "ладно")
# титры без данных о сегментах — как раньше (ниже — с данными)
cuts("Обзор новой модели. Спасибо за просмотр!", "Обзор новой модели.")
# после титра идёт речь — это не титр
keep("Ок, продолжение следует на следующей неделе")
keep("Спасибо за просмотр этого длинного отчёта, коллеги")
# одна фраза целиком не выбрасывается
keep("Спасибо за просмотр!")
# гейт по аудио: титр внутри речевого сегмента остаётся
keep("Это первая часть письма, продолжение следует.",
     [{"text": " Это первая часть письма, продолжение следует.", "start": 0.0, "end": 3.0,
       "no_speech_prob": 0.02, "avg_logprob": -0.2}])
# титр отдельным сегментом на тишине — режем
segs = [{"text": " Обзор новой модели.", "start": 0.0, "end": 2.0,
         "no_speech_prob": 0.02, "avg_logprob": -0.2},
        {"text": " Спасибо за просмотр!", "start": 2.1, "end": 3.5,
         "no_speech_prob": 0.7, "avg_logprob": -0.9}]
cuts("Обзор новой модели. Спасибо за просмотр!", "Обзор новой модели.", segs)
# титр после паузы, даже с низким no_speech_prob — режем
segs[1].update(no_speech_prob=0.1, start=5.0)
cuts("Обзор новой модели. Спасибо за просмотр!", "Обзор новой модели.", segs)
# титр сразу за речью и модель уверена — оставляем
segs[1].update(start=2.1, avg_logprob=-0.2)
keep("Обзор новой модели. Спасибо за просмотр!", segs)
# несколько титров подряд
cuts("Текст доклада. Продолжение следует. Субтитры сделал DimaTorzok", "Текст доклада.")
print("ok")
